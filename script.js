function getApplications() {
    return JSON.parse(localStorage.getItem("applications")) || [];
}

function applyForOpportunity(title) {

    let applications = getApplications();

    if (applications.includes(title)) {
        alert("You have already applied for this opportunity.");
        return;
    }

    applications.push(title);

    localStorage.setItem(
        "applications",
        JSON.stringify(applications)
    );

    updateApplicationsCounter();

    alert("✅ Application tracked successfully!");
}

function displayApplications() {

    const list = document.getElementById("applicationsList");

    if (!list) return;

    const applications = getApplications();

    list.innerHTML = "";

    if (applications.length === 0) {
        list.innerHTML = "<li>No applications tracked yet.</li>";
        return;
    }

    applications.forEach(function(item) {
        const li = document.createElement("li");
        li.textContent = item;
        list.appendChild(li);
    });
}

function clearApplications() {

    if (!confirm("Clear all tracked applications?")) {
        return;
    }

    localStorage.removeItem("applications");

    displayApplications();

    updateApplicationsCounter();

    alert("✅ Applications cleared!");
}

function updateApplicationsCounter() {

    const counter = document.getElementById("dashboardApplications");

    if (counter) {
        counter.textContent = getApplications().length;
    }
}

document.addEventListener("DOMContentLoaded", function () {

    updateApplicationsCounter();

    displayApplications();

    const btn = document.getElementById("clearApplicationsBtn");

    if (btn) {
        btn.onclick = clearApplications;
    }

});
/* =====================================================
   ADMIN PANEL
   ===================================================== */

function getAdminJobs() {
    return JSON.parse(localStorage.getItem("adminJobs")) || [];
}

function addJob() {

    const title = document.getElementById("jobTitle").value.trim();
    const company = document.getElementById("jobCompany").value.trim();
    const location = document.getElementById("jobLocation").value.trim();

    if (!title || !company || !location) {
        alert("Please complete all fields.");
        return;
    }

    let jobs = getAdminJobs();

    jobs.push({
        title: title,
        company: company,
        location: location
    });

    localStorage.setItem(
        "adminJobs",
        JSON.stringify(jobs)
    );

    document.getElementById("jobTitle").value = "";
    document.getElementById("jobCompany").value = "";
    document.getElementById("jobLocation").value = "";

    displayAdminJobs();

    alert("✅ Job added successfully!");
}

function displayAdminJobs() {

    const list = document.getElementById("adminJobsList");

    if (!list) return;

    const jobs = getAdminJobs();

    list.innerHTML = "";

    if (jobs.length === 0) {

        list.innerHTML = "<li>No jobs added yet.</li>";

        return;
    }

    jobs.forEach(function(job, index) {

        const li = document.createElement("li");

        li.innerHTML =
    "<strong>" + job.title + "</strong><br>" +
    job.company + "<br>" +
    job.location +
    "<br><br>" +

    "<button onclick='editAdminJob(" + index + ")'>✏️ Edit</button> " +

    "<button onclick='deleteAdminJob(" + index + ")'>🗑️ Delete</button>";

        list.appendChild(li);

    });

}

function deleteAdminJob(index) {

    let jobs = getAdminJobs();

    if (!confirm("Delete this job?")) {
        return;
    }

    jobs.splice(index, 1);

    localStorage.setItem("adminJobs", JSON.stringify(jobs));

    displayAdminJobs();
    displayWebsiteJobs();
}
function editAdminJob(index) {

    const jobs = getAdminJobs();

    document.getElementById("jobTitle").value = jobs[index].title;
    document.getElementById("jobCompany").value = jobs[index].company;
    document.getElementById("jobLocation").value = jobs[index].location;

    deleteAdminJob(index);
}
document.addEventListener("DOMContentLoaded", function () {
    displayAdminJobs();
});

/* =====================================================
   SHOW ADMIN JOBS ON JOBS PAGE
   ===================================================== */

function displayWebsiteJobs() {

    const container = document.getElementById("adminJobsContainer");

    if (!container) return;

    const jobs = getAdminJobs();

    container.innerHTML = "";

    if (jobs.length === 0) {
        container.innerHTML = "<p>No admin jobs available yet.</p>";
        return;
    }

    jobs.forEach(function(job) {

        const card = document.createElement("div");

        card.className = "card";

        card.innerHTML = `
            <h3>${job.title}</h3>
            <p><strong>Company:</strong> ${job.company}</p>
            <p><strong>Location:</strong> ${job.location}</p>

         <button onclick="saveSavedJob('${job.title}')">
    ❤️ Save Job
</button>

            <button onclick="applyForOpportunity('${job.title}')">
                📩 Apply
            </button>
        `;

        container.appendChild(card);

    });

}

document.addEventListener("DOMContentLoaded", function () {
    displayWebsiteJobs();
});
