/* =====================================================
   JOB SEARCH + FILTERS
   ===================================================== */

document.addEventListener("DOMContentLoaded", function () {

    const searchInput =
        document.getElementById(
            "jobSearch"
        ) ||
        document.getElementById(
            "searchInput"
        );

    const provinceFilter =
        document.getElementById(
            "provinceFilter"
        );

    const categoryFilter =
        document.getElementById(
            "categoryFilter"
        );

    const jobs =
        document.querySelectorAll(
            ".job"
        );

    function filterJobs() {

        const searchValue =
            searchInput
                ? searchInput.value.toLowerCase()
                : "";

        const provinceValue =
            provinceFilter
                ? provinceFilter.value
                : "";

        const categoryValue =
            categoryFilter
                ? categoryFilter.value
                : "";

        jobs.forEach(function (job) {

            const text =
                job.innerText.toLowerCase();

            const province =
                job.dataset.province || "";

            const category =
                job.dataset.category || "";

            const matchesSearch =
                text.includes(searchValue);

            const matchesProvince =
                !provinceValue ||
                province === provinceValue;

            const matchesCategory =
                !categoryValue ||
                category === categoryValue;

            if (
                matchesSearch &&
                matchesProvince &&
                matchesCategory
            ) {

                job.style.display = "";

            } else {

                job.style.display = "none";

            }

        });

    }

    if (searchInput) {

        searchInput.addEventListener(
            "input",
            filterJobs
        );

    }

    if (provinceFilter) {

        provinceFilter.addEventListener(
            "change",
            filterJobs
        );

    }

    if (categoryFilter) {

        categoryFilter.addEventListener(
            "change",
            filterJobs
        );

    }

});


